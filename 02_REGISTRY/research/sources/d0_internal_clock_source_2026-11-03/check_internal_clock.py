def create_ops():
    out=[]
    for mu in range(4):
        C=np.zeros((16,16))
        for mask in range(16):
            if not (mask>>mu)&1:
                C[mask|(1<<mu),mask]=(-1)**sum((mask>>j)&1 for j in range(mu))
        out.append(C)
    for mu in range(4):
        for nu in range(4):
            require(np.max(abs(out[mu].T@out[nu]+out[nu]@out[mu].T-(np.eye(16) if mu==nu else 0)))==0,'full16 CAR')
    return out


