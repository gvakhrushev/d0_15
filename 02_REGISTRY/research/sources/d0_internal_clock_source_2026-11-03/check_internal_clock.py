def symbolic_clock() -> dict:
    a = sp.symbols('a', real=True)
    scale, w = sp.symbols('scale w', positive=True)
    eta = sp.diag(1, -1, -1, -1)
    e = sp.Matrix([[1,a,0,0],[-a,1,0,0],[0,0,w*sp.sqrt(1+a*a),0],
                   [0,0,0,sp.sqrt(1+a*a)]])/(scale*sp.sqrt(1+a*a))
    F = sp.simplify(e.inv())
    g = sp.simplify(e.T*eta*e)
    positive = sp.simplify(e.T*e)
    expected = sp.diag(1,1,w*w,1)/scale**2
    require(sp.simplify(positive-expected)==sp.zeros(4), 'exact positive pairing')
    raw_grade_one = sp.Matrix([1,0,0,0])
    current = sp.simplify(F*raw_grade_one)
    norm = sp.simplify((current.T*g*current)[0])
    require(norm==1, 'native P1 current is unit timelike, not external')
    b = sp.simplify(g*current)
    require(sp.simplify(-g+2*b*b.T/norm-positive)==sp.zeros(4), 'owned P1 reflection identity')
    dclock = sp.Matrix([1,a,0,0])
    grad = sp.simplify(g.inv()*dclock)
    qclock = sp.simplify((dclock.T*grad)[0])
    require(qclock==scale**2*(1+a*a), 'actual clock has positive Lorentz norm')
    require(sp.simplify(grad/sp.sqrt(qclock)-current)==sp.zeros(4,1), 'current generated by internal clock')
    require(sp.simplify(g.det()+w*w/scale**8)==0, 'Lorentz determinant')
    require(sp.simplify(e.det()-w/scale**4)==0, 'coframe orientation')
    x = sp.symbols('x', real=True)
    af=sp.Function('a')(x)
    clock_form=sp.Matrix([1,af,0,0])
    # d(dt+a(x)dx)=0. Its positive scalar multiple u has Frobenius u wedge du=0.
    coords=sp.symbols('t x y z', real=True)
    clock_form=clock_form.subs(x,coords[1])
