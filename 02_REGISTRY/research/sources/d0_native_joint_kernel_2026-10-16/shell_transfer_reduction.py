def require(condition, label):
    if not bool(condition):
        raise ArithmeticError("shell_transfer_reduction:" + label)


def _load(name):
    path = HERE/(name+".py")
    require(hashlib.sha256(path.read_bytes()).hexdigest() == PINS[path.name],
            "owned_definition_pin:"+path.name)
    spec = importlib.util.spec_from_file_location("shell_transfer_"+name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _zero(matrix):
    entries = matrix if isinstance(matrix, s.MatrixBase) else (matrix,)
    return all(s.cancel(value) == 0 for value in entries)


def _pairs(q):
    return tuple((k, tuple((k[r]+q[r]) % 8 for r in range(4)))
                 for k in SHELL
                 if tuple((k[r]+q[r]) % 8 for r in range(4)) in SHELL)


def _gauge_column(axial, legs, kappa, operator):
    column = s.zeros(31, 1)
    rotation = s.diag(0, operator.cross(axial))
    for r in range(4):
        column[4*r:4*r+4, :] = rotation*legs[r]
        column[16+3*r:19+3*r, :] = kappa[r]*axial
    return column


def _image_generators(case, chart, legs, kappa, operator, check):
    """Algebraically reduce every full chart column to the claimed image.

    The removed remainder is a sum of explicit common spatial motion,
    observer coordinates, and inactive-role Cartesian coefficient jets.
    No Fock projection or omitted density entries establish the upper bound.
    """
    selected = case["columns"]
    killed = case["killed_active"]
    inactive = case["inactive"]
    basis = chart["basis31"]
    active_columns = tuple(c for c in selected if c < 3)
    active_map = (s.Matrix.hstack(*[basis[16:19, c] for c in active_columns])
                  if active_columns else None)
    if active_map is not None:
        determinant = s.cancel(active_map.det())
        b = -legs[0][3]
        check(_zero(determinant+kappa[0]**2/(3*b)),
              "relative_active_angular_map_nonzero_exact_formula")
        inverse = active_map.inv()
    for j in range(basis.cols):
        column = basis[:, j]
        observer = s.zeros(31, 1)
        observer[28:31, :] = column[28:31, :]
        axial = column[16+3*killed:19+3*killed, :]/kappa[killed]
        remainder = column-observer-_gauge_column(axial, legs, kappa, operator)
        if active_map is not None:
            coefficients = inverse*remainder[16:19, :]
            for coefficient, c in zip(coefficients, active_columns):
                remainder -= coefficient*basis[:, c]
        for c in selected:
            if c in active_columns:
                continue
            role = next(r for r in inactive if any(basis[16+3*r:19+3*r, c]))
            w = legs[role][1:4, :]
            axial = remainder[16+3*role:19+3*role, :]
            coefficient = (w.T*axial)[0]/(w.T*w)[0]
            remainder -= coefficient*basis[:, c]
        forbidden = list(range(16, 31))
        forbidden += [4*r+i for r in range(4) if r not in inactive for i in range(4)]
        check(_zero(remainder[forbidden, :]),
              "full_column_decomposes_into_image_plus_retained_kernel_"+str(j))


def _selected_minor(case, basis, legs, creators, operator):
    """Evaluate only the required actual X entries, not a 512-row census."""
    k, l = _pairs(case["q"])[0]
    Dk, lambda_k = operator.dirac(k, legs, creators)
    Dl, lambda_l = operator.dirac(l, legs, creators)
    matrix = s.zeros(len(case["rows"]), len(case["columns"]))
    for j, column in enumerate(case["columns"]):
        J = operator.first_jet(basis[:, column], legs, k, l, creators)
        for i, flat in enumerate(case["rows"]):
            row, col = divmod(flat, 16)
            matrix[i, j] = s.cancel(sum(Dl[row, h]*J[h, col]
                                       +J[row, h]*Dk[h, col] for h in range(16)))
    return matrix, (lambda_k, lambda_l)


