def port_check():
    import sympy as sp
    ne,digest=load_control()
    n=9
    g=ne.Gate("G",(1,))
    cx=ne.Gate("CX",(0,1))
    word=(g,)*n+(cx,)+(g,)*n+(cx,)
    e=ne.Execution(2,(),(),word,report_bits=(0,1))
    body=ne.execution_from_json(ne.canonical_json(e),max_qubits=2,max_expanded_stages=len(word))
    w=ne.word_matrix(body,max_qubits=2,max_expanded_stages=len(word))
    # Avoid symbolic powers by multiplying once in the native algebraic field.
    from sympy.polys.matrices import DomainMatrix
    def dm(x):
        return DomainMatrix.from_Matrix(x).convert_to(ne.GOLDEN_FIELD)
    w=dm(w)
    rotation=dm(ne.G_LOCAL)**(2*n)
    need((w[:2,:2]-rotation).is_zero_matrix and
         (w[2:,2:]-dm(sp.eye(2))).is_zero_matrix and
         w[:2,2:].is_zero_matrix and w[2:,:2].is_zero_matrix,
         "true finite native word rotates only D=0 and preserves all three marked sectors")
    return digest,len(word)


def main():
    digest,calls=port_check()
    p=(span(5).sqrt()-1)/2
    a=p.sqrt()
    one=span(1)
    def coincide(x,y):
        return (x-y).lo<=0<=(x-y).hi
    mu=[p,p**3]
    def f(q):
        return a*(1-q).sqrt()+a*p*q.sqrt()
    def ell(q,u):
        return (1/(1-q).sqrt()-u*p/q.sqrt())/(2*((1-q).sqrt()+u*p*q.sqrt()))
    gamma=[p+a*p**2,a*p+p**2]
    cond=[p**2,p]
    ratio=gamma[1]/gamma[0]
    need(coincide(f(cond[0]),gamma[0]) and coincide(f(cond[1]),gamma[1]),"both recovered cold sectors")
    need(0<ratio.lo<=ratio.hi<1 and (4*gamma[0]**2).lo>1,"late growing-law domination")
    lower=ell(p**2,one)
    need(lower.lo>0,"uniform all-noise susceptibility on closed noisy collar")
    q=span(F(7,16))
    # Full resolved path, actual canonical masses include the born dark leaf.
    for k in range(1,6):
        total=span(0)
        for t in (0,1):
            qw=q if t else 1-q
            for ds in product((0,1),repeat=k):
                mass=mu[t]
                prob=qw
                for d in ds:
                    mass*=mu[d]
                    prob*=cond[t] if d else 1-cond[t]
                total+=(mass*prob).sqrt()
        formula=gamma[0]**k*a*((1-q).sqrt()+ratio**k*p*q.sqrt())
        need(coincide(total,formula),"full joint-effect Hellinger envelope and causal saturation")
    # Explicit finite recovery in the two sectors. 19 theta is the residual
    # tail angle after G^9 CX G^9 CX, and the initialized 11 remains dark.
    c,s=span(1),span(0)
    for j in range(19):
        c,s=c*a-s*p,s*a+c*p
    finite_g0=p*c+a*p**2
    finite_g1=a*p*c+p**2
    need(0<(finite_g0-finite_g1).lo and gamma[0].lo>finite_g0.hi and
         c.lo>F(995,1000),"an actual finite correction separates both true sectors")
    # A genuine singular, nondiagonal old Gram: eigenvalues (3/4, 0),
    # eigenbasis rotated by cos=3/5, sin=4/5. A two-sided old tangent
    # is generated by moving the nonzero eigenvalue and rotating the basis.
    lam=F(3,4)
    aold=[[F(27,100),F(9,25)],[F(9,25),F(12,25)]]
    v=(F(3,5),F(4,5))
    nvec=(-v[1],v[0])
    dl=F(1,8)
    dA=[[dl*v[i]*v[j]+lam*(v[i]*nvec[j]+nvec[i]*v[j]) for j in range(2)] for i in range(2)]
    need(aold[0][0]*aold[1][1]==aold[0][1]**2 and sum(aold[i][i] for i in range(2))==lam,
         "nonscalar old Gram with a dark column")
    z=F(1,2**20)
    d=1-z
    N,K=4,9
    qs=[span(F(2,5)),span(F(7,16)),span(F(19,42)),span(F(10,21))]
    ms=[1,1,1,K]
    gs=[F(1,2),F(4,5),F(5,4),F(3,2)]
    u=[ratio**m for m in ms]
    signal=sum((g*ell(qi,ui) for g,qi,ui in zip(gs,qs,u)),span(0))
    cold=span(1)
    for qi,m,ui in zip(qs,ms,u):
        cold*=gamma[0]**m*a*((1-qi).sqrt()+ui*p*qi.sqrt())
    b=z*cold**2
    wm=b*lam/(d+b*lam)
    gain=2*wm*signal
    # (dI+b A)^-1, trace against the complete old direction including rotation.
    rr=[[span(F(i==j))/d-b*aold[i][j]/(d*(d+b*lam)) for j in range(2)] for i in range(2)]
    old=-b*sum((rr[i][j]*dA[j][i] for i in range(2) for j in range(2)),span(0))
    need(coincide(old/gain,-dl/(2*lam*signal)),"past derivative cancels even tiny exact cold factor")
    # The actual nuclear norm is ≤ |dl|+2 lam by rank-one decomposition.
    op_bound=(dl+2*lam)/(2*d*lam*signal)
    need((-old/gain).hi<op_bound.lo,"bounded moving archive independent of cold powers")
    # Independent physical susceptibility of D at branch t=0, all fields frozen.
    omega0=(1-q).sqrt()/((1-q).sqrt()+ratio**K*p*q.sqrt())
    effect=omega0*ell(cond[0],one)
    need(effect.lo>0,"keeping T alone cannot kill an allowed change of a D|T probability")
    # A raw r=0 tail turn does not change any recorded outcome but changes cold.
    qevent=span(F(2,5))
    A0=p-(p+a*p)*qevent
    graw=p+a*p+(2*p**2/a)**K*(p**2+a*p)
    raw_residual=(p/a)*A0/graw
    need(raw_residual.lo>0,"bare-copy family has a genuine fixed-effect completion slope")
    print(json.dumps({"status":"PASS","owner_sha256":digest,"joint_paths_checked_through":5,
        "recovered_gamma_0":gamma[0].fmt(14),"recovered_gamma_1":gamma[1].fmt(14),
        "late_heat_factor_4_gamma0_squared":(4*gamma[0]**2).fmt(14),
        "uniform_susceptibility_lower":lower.fmt(14),"literal_correction_calls":calls,
        "actual_finite_gamma0":finite_g0.fmt(14),"actual_finite_gamma1":finite_g1.fmt(14),
        "singular_moving_Gram_gain":gain.fmt(20),"normalized_old_row":(old/gain).fmt(14),
        "positive_late_effect_row_per_2w":effect.fmt(14),
        "uncorrected_fixed_effect_tail_row_over_Q_gain":raw_residual.fmt(14),
        "scope":"Ideal/approximable complete fixed-joint-effect comparison; not a microscopic tariff or full eight-setting compilation."},
        ensure_ascii=False,indent=2))


if __name__=="__main__":
    main()
